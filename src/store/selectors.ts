// ─── Agent statuses (derived from active runs + open gates) ───────────────────

export function selectAgentStatus(state: AppState, agent: AgentId): AgentStatus {
  const hasActiveRun = state.runs.some(r => r.agent === agent && r.status === 'running')
  if (hasActiveRun) return 'running'

  // 'flow' is blocked while any gate is open
  if (agent === 'flow') {
    const anyOpen = state.gates.some(g => g.status === 'open')
    if (anyOpen) return 'blocked'
  }

  // Agent is 'running' if stories are currently in its stage
  const stageMap: Record<AgentId, string[]> = {
    onboarding: ['backlog'],
    ba:         ['requirements'],
    dev:        ['plan', 'build'],
    qa:         ['test'],
    flow:       [],
  }
  const inStage = state.stories.some(s => stageMap[agent].includes(s.stage))
  if (inStage) return 'running'

  return 'idle'
}

