// Dev sprint summary stats — derived from runs
export function selectDevSprintStats(state: AppState) {
  const devRuns = state.runs.filter(r => r.agent === 'dev' && r.status === 'done')
  const totalRuns = devRuns.length
  const avgRevisions = totalRuns > 0
    ? (devRuns.reduce((acc, r) => {
        const story = state.stories.find(s => s.key === r.storyKey)
        return acc + (story?.artifacts.plan?.revisions.length ?? 1)
      }, 0) / totalRuns).toFixed(1)
    : '—'

  const minutesPerRun = devRuns
    .map(r => {
      const story = state.stories.find(s => s.key === r.storyKey)
      return story?.stageMinutes.plan ?? 0
    })
    .filter(m => m > 0)
  const avgMinutes = minutesPerRun.length > 0
    ? Math.round(minutesPerRun.reduce((a, b) => a + b, 0) / minutesPerRun.length)
    : 0

  return [
    { label: 'Runs this sprint',    value: String(totalRuns),          sub: `${totalRuns} plans generated` },
    { label: 'Plan iterations avg', value: avgRevisions,               sub: 'corrections per run'          },
    { label: 'Avg run time',        value: avgMinutes ? `${avgMinutes} min` : '—', sub: '↓ 6 min vs prev' },
    { label: 'Drift flags',         value: '0',                        sub: 'this sprint'                  },
  ]
}

