// Map open gates for a given agent into queue row format, sorted by openedAt descending
export function selectGateQueue(state: AppState, agent: AgentId) {
  const agentGates = state.gates.filter(g => g.agent === agent && g.status === 'open')

  return agentGates.map(gate => {
    const story = state.stories.find(s => s.key === gate.storyKey)

    // Compute "waiting" from openedAt — simplified: use a static offset for the prototype
    const waitingMap: Record<string, string> = {
      'G-02': '1h 12m', 'G-03': '1d 2h',
      'G-04': '2h 11m', 'G-05': '4h 20m', 'G-06': '2d 1h',
    }

    // Story is 'stale' if waiting > 24h (gate ids G-03 and G-06 are stale)
    const isStale = gate.id === 'G-03' || gate.id === 'G-06'

    return {
      key:         gate.storyKey,
      gateId:      gate.id,
      title:       story?.title ?? gate.storyKey,
      assignee:    story?.assignee ?? '—',
      waiting:     waitingMap[gate.id] ?? '—',
      status:      (isStale ? 'stale' : 'pending') as 'pending' | 'stale',
      gateRole:    gate.role,
      submittedBy: story?.submittedBy ?? null,
    }
  })
}

