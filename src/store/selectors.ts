// Chain trail: derives 4 chips (REQ → PLAN → DIFF → TESTS) from story stage
export function selectChainTrail(state: AppState, storyKey: string) {
  const story = state.stories.find(s => s.key === storyKey)
  if (!story) return []

  const stageOrder: Record<string, number> = {
    backlog: -1, requirements: 0, plan: 1, build: 2, test: 3, accept: 4, done: 5,
  }
  const idx = stageOrder[story.stage] ?? -1

  const plan = story.artifacts.plan
  const diff = story.artifacts.diff

  const chips = [
    {
      type: 'REQ', label: 'Requirement', id: story.key,
      textColor: '#1D4ED8', bg: '#EFF6FF', accent: '#3B82F6',
      summary: story.title,
      linkStatus: idx > 0 ? 'done' : idx === 0 ? 'current' : 'pending',
    },
    {
      type: 'PLAN', label: 'Plan', id: plan?.id ?? '—',
      textColor: '#6D28D9', bg: '#F5F3FF', accent: '#8B5CF6',
      summary: plan ? `${story.title} · rev ${plan.revisions.length} of ${plan.revisions.length}` : 'Not yet generated',
      linkStatus: idx > 1 ? 'done' : idx === 1 ? 'current' : 'pending',
    },
    {
      type: 'DIFF', label: 'Diff', id: diff?.mr ?? '—',
      textColor: '#C2410C', bg: '#FFF7ED', accent: '#F97316',
      summary: diff
        ? `MR ${diff.mr}: feat/${storyKey.toLowerCase()} → main · ${diff.hunks} hunks · +${diff.additions} −${diff.deletions}`
        : 'Not yet generated — awaiting plan approval',
      linkStatus: idx > 2 ? 'done' : idx === 2 ? 'current' : 'pending',
    },
    {
      type: 'TESTS', label: 'Tests', id: 'SPEC-' + storyKey.split('-')[1],
      textColor: '#15803D', bg: '#F0FDF4', accent: '#16A34A',
      summary: story.artifacts.tests
        ? `Specs generated by QA agent · skill v2`
        : 'Not yet generated — awaiting diff',
      linkStatus: idx > 3 ? 'done' : idx === 3 ? 'current' : 'pending',
    },
  ] as const

  return chips
}

