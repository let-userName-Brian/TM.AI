// ─── Flow analytics ───────────────────────────────────────────────────────────

export function selectStageTimeline(state: AppState, storyKey: string) {
  const story = state.stories.find(s => s.key === storyKey)
  if (!story) return []

  const stages = [
    { name: 'Onboard',      stageKey: 'backlog'       as const, display: (m: number) => `${m} min` },
    { name: 'Requirements', stageKey: 'requirements'  as const, display: (m: number) => m >= 60 ? `${(m/60).toFixed(1)} h` : `${m} min` },
    { name: 'Plan',         stageKey: 'plan'          as const, display: (m: number) => m >= 60 ? `${(m/60).toFixed(1)} h` : `${m} min` },
    { name: 'Build',        stageKey: 'build'         as const, display: (m: number) => m >= 60 ? `${(m/60).toFixed(1)} h` : `${m} min` },
    { name: 'Test',         stageKey: 'test'          as const, display: (m: number) => m >= 60 ? `${(m/60).toFixed(1)} h` : `${m} min` },
  ]

  const stageOrder: Record<string, number> = {
    backlog: -1, requirements: 0, plan: 1, build: 2, test: 3, accept: 4, done: 5,
  }
  const storyIdx = stageOrder[story.stage] ?? -1

  const result = stages.map(s => {
    const minutes = story.stageMinutes[s.stageKey]
    const stageIdx = stageOrder[s.stageKey] ?? -1
    const pending = stageIdx > storyIdx || minutes == null
    return {
      name: s.name,
      display: minutes != null ? s.display(minutes) : 'next day',
      units: minutes ?? 26,
      pending,
    }
  })

  // Add Accept as always-pending if story isn't done/accept
  const acceptPending = story.stage !== 'done' && story.stage !== 'accept'
  result.push({ name: 'Accept', display: 'next day', units: 26, pending: acceptPending })

  return result
}

export function selectStoryComparison(state: AppState, s1Key: string, s2Key: string) {
  const s1 = state.stories.find(s => s.key === s1Key)
  const s2 = state.stories.find(s => s.key === s2Key)
  if (!s1 || !s2) return []

  const cycleTime = (story: typeof s1) => {
    const mins = Object.values(story.stageMinutes).reduce<number>((a, b) => a + (b ?? 0), 0)
    return (mins / (60 * 8)).toFixed(1) + ' d'  // assume 8h days
  }

  const tokens = (storyKey: string) => {
    const t = state.runs.filter(r => r.storyKey === storyKey).reduce((a, r) => a + r.tokensUsed, 0)
    return t >= 1000 ? `${(t / 1000).toFixed(1)}k` : String(t)
  }

  const archTouches = (storyKey: string) => {
    return state.gates.filter(g => g.storyKey === storyKey && g.role === 'ba').length
  }

  const driftFlags = (story: typeof s1) => {
    const specs = story.artifacts.tests?.specs.flatMap(f => f.cases) ?? []
    return specs.filter(c => c.result === 'fail').length
  }

  const planRevisions = (story: typeof s1) => story.artifacts.plan?.revisions.length ?? 1

  return [
    { label: 'Plan iterations',   s1: String(planRevisions(s1)), s2: String(planRevisions(s2)), direction: 'down' as const, better: 'down' as const },
    { label: 'Cycle time',        s1: cycleTime(s1),             s2: cycleTime(s2),             direction: 'down' as const, better: 'down' as const },
    { label: 'Tokens',            s1: tokens(s1Key),             s2: tokens(s2Key),             direction: 'down' as const, better: 'down' as const },
    { label: 'Architect touches', s1: String(archTouches(s1Key)), s2: String(archTouches(s2Key)), direction: 'down' as const, better: 'down' as const },
    { label: 'Drift flags',       s1: String(driftFlags(s1)),    s2: String(driftFlags(s2)),    direction: 'down' as const, better: 'down' as const },
  ]
}

