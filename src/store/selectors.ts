// Summary counts derived from spec cases
export function selectTestSummary(state: AppState, storyKey: string) {
  const specs = selectSpecs(state, storyKey)
  const cases = specs.flatMap(f => f.cases)
  return {
    pass:    cases.filter(c => c.result === 'pass').length,
    fail:    cases.filter(c => c.result === 'fail').length,
    total:   cases.length,
  }
}

